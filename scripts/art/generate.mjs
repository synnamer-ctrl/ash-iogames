// Generates every SVG illustration in public/assets and the typed manifest
// in src/data/asset-manifest.ts. Run with `npm run assets`.
import { mkdirSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Ctx, svgDoc, hashSeed } from './lib.mjs';
import { shared } from './shared.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
// `--doodle` writes a hand-drawn variant of every asset to public/assets-doodle/ (no manifest change, the game keeps its own set)
const doodle = process.argv.includes('--doodle');
const outRoot = join(root, 'public', doodle ? 'assets-doodle' : 'assets');
const groups = [shared];
for (const mod of ['town', 'garden', 'workshop', 'build', 'ui', 'backgrounds']) {
  try {
    const m = await import(`./${mod}.mjs`);
    groups.push(m.assets);
  } catch (e) {
    if (e.code !== 'ERR_MODULE_NOT_FOUND') throw e;
  }
}
const all = groups.flat();

// hand-drawn wobble: displace every edge with fractal noise, seeded per asset so each drawing wobbles differently
function doodleFilter(a) {
  const seed = hashSeed(a.key) % 1000;
  return `<filter id="doodle" filterUnits="userSpaceOnUse" x="-12" y="-12" width="${a.w + 24}" height="${a.h + 24}" color-interpolation-filters="sRGB">` +
    `<feTurbulence type="fractalNoise" baseFrequency="0.045" numOctaves="2" seed="${seed}" result="n"/>` +
    `<feDisplacementMap in="SourceGraphic" in2="n" scale="5" xChannelSelector="R" yChannelSelector="G"/></filter>`;
}
function doodleWrap(a, body) {
  return `<g filter="url(#doodle)">${body}</g>`;
}
const seen = new Set();
const manifest = {};
for (const a of all) {
  if (seen.has(a.key)) throw new Error('Duplicate asset key ' + a.key);
  seen.add(a.key);
  const c = new Ctx(a.key);
  const body = a.draw(c);
  const defs = a.defs ? a.defs(c) : '';
  const path = `assets/${a.dir}/${a.key}.svg`;
  mkdirSync(join(outRoot, a.dir), { recursive: true });
  if (doodle) {
    writeFileSync(join(outRoot, a.dir, `${a.key}.svg`), svgDoc(a.w, a.h, doodleWrap(a, body), { defs: defs + doodleFilter(a) }));
    continue;
  }
  writeFileSync(join(root, 'public', path), svgDoc(a.w, a.h, body, { defs }));
  manifest[a.key] = { path, w: a.w, h: a.h, dir: a.dir, ...(a.anchors ? { anchors: a.anchors } : {}) };
}
if (doodle) {
  console.log(`Wrote ${all.length} doodle assets to public/assets-doodle.`);
  process.exit(0);
}
const ts = `// AUTO-GENERATED by scripts/art/generate.mjs — do not edit by hand.
export interface AssetEntry { path: string; w: number; h: number; dir: string; anchors?: Record<string, readonly [number, number]> }
export const ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, AssetEntry>;
export type AssetKey = keyof typeof ASSET_MANIFEST;
`;
writeFileSync(join(root, 'src', 'data', 'asset-manifest.ts'), ts);
console.log(`Generated ${all.length} illustrations.`);
